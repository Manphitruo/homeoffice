#include <stdlib.h>
#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	char const	*ptr;
	int		i;

	i = ft_strlen(s);
	i--;
	while (s[i])
	{
		ptr = &s[i];
		if (s[i] == c)
			return ((char *)ptr);
		i--;
	}
	return (NULL);
}
