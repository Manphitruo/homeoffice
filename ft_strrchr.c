#include <stdlib.h>
#include "libft.h"

char	*ft_strrchr(char const *s, int c)
{
	int		i;

	i = (int)ft_strlen(s);
	if ((char)c == 0)
		return ((char *)&s[ft_strlen(s)]);
	while (i >= 0)
	{
		if (s[i] == (char)c)
			return ((char *)&s[i]);
		i--;
	}
	return (NULL);
}

