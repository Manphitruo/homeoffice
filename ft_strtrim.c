#include <stdlib.h>
#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*ptr;
	size_t	start;
	size_t	end;

	if (!s1 || !set)
		return (NULL);
	if (s1[0] == '\0' || set[0] == '\0')
		return (ft_strdup(""));
	start = 0;
	end = ft_strlen(s1);
	while (start < end && ft_strchr(set, s1[start]))
		start++;
	while (start < end && ft_strchr(set, s1[end]))
		end--;
	ptr = malloc((end - start) + 1);
	if (!ptr)
		return (NULL);
	while (s1[start] && start < end)
	{
		ptr[start] = s1[start];
		start++;
	}
	ptr[start] = '\0';
	return (ptr);
}
