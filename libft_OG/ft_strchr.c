#include "libft.h"

char	*ft_strchr(char const *s, int c)
{
	int		i;

	i = 0;
	if ((char)c == 0)
		return ((char *)&s[ft_strlen(s)]);
	while (s[i])
	{
		if (s[i] == (char)c)
			return ((char *)&s[i]);
		i++;
	}
	if ((char)c == s[i])
		return ((char *)&s[i]);
	return (NULL);
}

