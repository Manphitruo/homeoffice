#include <stdlib.h>
#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*ptr;

	while (*lst != NULL)
	{
		ptr = (*lst)->next;
		ft_lstdelone(*lst,del);
		*lst = ptr;
	}
	*lst = NULL;
}
