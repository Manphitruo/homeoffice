#include <stdlib.h>
#include "libft.h"

void *ft_calloc(size_t n, size_t size)
{
	void	*ptr;

	if (n == 0 || size == 0)
	{
		ptr = malloc(1);
		if (!ptr)
			return(NULL);
		return (ptr);
	}
	if (n > (size_t) - 1 / size)
		return (NULL);
	ptr = malloc(n * size);
	if (!ptr)
		return (NULL);
	ft_bzero(ptr, n * size);
	return (ptr);
}
