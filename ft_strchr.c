#include <stdlib.h>

char	*ft_strchr(const char *s, int c)
{
	char	*ptr;
	int		i;

	i = 0;
	while (s[i])
	{
		ptr = &s[i];
		if (s[i] == c)
			return (ptr);
		i++;
	}
	return (NULL);
}
